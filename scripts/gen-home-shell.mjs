// Generates the homepage's static above-the-fold shell and bakes it into
// index.html between the GENERATED:HOME-SHELL markers.
//
// WHY THIS EXISTS
// The editorial site is a client-rendered SPA: nothing paints until React, the
// shared shell scripts, and the route's page bundle have all loaded and run.
// The July 2026 measurement on the homepage (mobile emulation, 4x CPU, 1.6 Mbps)
// put first paint at 4.7 s and LCP at 6.2 s, and the LCP element was the hero
// dek paragraph — text, not the hero photo. In other words the homepage's Core
// Web Vitals were gated entirely on JavaScript, not on bytes.
//
// So the top of the homepage is rendered here, offline, into plain HTML that
// ships inside index.html and paints on the first byte. React replaces it on
// boot (createRoot().render() replaces #root's children, and app.jsx removes
// any leftover #home-shell explicitly).
//
// WHY index.html AND NOT THE EDGE WORKER
// edge/seo.js cannot do this: routing is asset-first, so a request for "/"
// matches index.html and never invokes the Worker (see wrangler.jsonc). Baking
// the markup into the asset is both the only option and the fastest one — the
// homepage costs zero Worker invocations. The Worker DOES run for every other
// SPA route, and it strips this block there, so no other page pays for it.
//
// FIDELITY IS THE WHOLE GAME
// The shell must be markup-identical to what React renders a moment later, or
// the swap causes layout shift on the site's most-landed-on page (CLS is ~0
// today and stays that way). That is why this script renders the REAL Header
// and HomeHero components out of components.jsx / page-home.jsx rather than a
// hand-written copy: fidelity by construction, and `--check` fails the build
// if the sources drift from the baked output.
//
// NOTHING DATE-DERIVED MAY BE BAKED IN
// index.html is cached hard at the edge and in browsers, so any date-derived
// text would go stale. One slot is date-derived: the hero's issue label
// (window.SITE.issueDetail, whose month tracks the clock — see data.js). It is
// emitted as a stable-height blank and filled by React on boot. The script
// asserts the slot exists, so removing or renaming it fails loudly here
// instead of silently shipping a frozen month name.
//
// Usage:
//   node scripts/gen-home-shell.mjs           # rewrite the block in index.html
//   node scripts/gen-home-shell.mjs --check   # exit 1 if the block is stale

import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const babel = require("@babel/core");
const presetReact = require("@babel/preset-react");
const transformBlockScoping = require("@babel/plugin-transform-block-scoping");
const React = require("react");
// react-dom 19 warns that `fetchpriority` should be `fetchPriority`. The site
// builds against React 18, which has no special handling for either spelling
// and emits whatever components.jsx authors — so lowercase is correct here and
// the warning is noise that would look like a failure in `npm run check`.
// Patched before react-dom loads because it captures console.error on import.
const realConsoleError = console.error;
console.error = (...args) => {
  // React formats this one as ("Invalid DOM property `%s`...", "fetchpriority"),
  // so the property name is an interpolated argument, not part of args[0].
  const joined = args.map((a) => String(a)).join(" ");
  if (joined.includes("Invalid DOM property") && joined.includes("fetchpriority")) return;
  realConsoleError(...args);
};
const { renderToStaticMarkup } = require("react-dom/server");

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const INDEX = path.join(ROOT, "index.html");

const CHECK = process.argv.includes("--check");

const START =
  "<!-- GENERATED:HOME-SHELL:START — regenerated by scripts/gen-home-shell.mjs; edit page-home.jsx (HomeHero) or components.jsx (Header), not this markup -->";
const END = "<!-- GENERATED:HOME-SHELL:END -->";

// The two components the shell renders, and the files that must be evaluated
// (in index.html's load order) for them to exist.
const SOURCES = ["components.jsx", "page-home.jsx"];

// ---------------------------------------------------------------------------
// Evaluate the real page sources in one vm context, exactly as the browser
// evaluates the compiled /dist files in one shared script scope.
// ---------------------------------------------------------------------------
function compile(src, filename) {
  return babel.transformSync(src, {
    presets: [[presetReact, { runtime: "classic" }]],
    plugins: [transformBlockScoping],
    filename,
    babelrc: false,
    configFile: false,
    comments: false,
    compact: false,
  }).code;
}

// window.SITE is read by both the masthead and the hero. Harvest it from
// data.js rather than duplicating the strings.
function loadSite() {
  const sandbox = {
    window: {},
    document: { createElement: () => ({}), querySelector: () => null, head: {} },
    navigator: { userAgent: "node" },
    console,
  };
  vm.createContext(sandbox);
  for (const f of ["affiliate.js", "data.js"]) {
    vm.runInContext(fs.readFileSync(path.join(ROOT, f), "utf8"), sandbox, { filename: f });
  }
  if (!sandbox.window.SITE) {
    console.error("data.js did not populate window.SITE");
    process.exit(2);
  }
  return sandbox.window.SITE;
}

// Mirror of routeToPath in app.jsx for the handful of route keys the masthead
// and hero link to. app.jsx is not evaluated here (its boot block mounts React
// and touches the DOM), so this stays a small hand-kept mirror; the assertions
// at the bottom catch an href that stops looking like a path.
function routeToPath(route) {
  if (!route || route === "home") return "/";
  if (route.startsWith("cat:")) return `/section/${route.slice(4)}`;
  if (route.startsWith("a:")) return `/articles/${route.slice(2)}`;
  return `/${route}`;
}

function buildSandbox(site) {
  const noop = () => {};
  const el = () => ({
    style: {},
    classList: { add: noop, remove: noop, contains: () => false },
    setAttribute: noop, appendChild: noop, addEventListener: noop,
    removeEventListener: noop, querySelector: () => null, querySelectorAll: () => [],
    remove: noop, getElementById: () => null,
  });
  const sandbox = {
    React,
    ReactDOM: { createRoot: () => ({ render: noop }) },
    window: {},
    document: Object.assign(el(), {
      getElementById: () => null, createElement: () => el(), querySelector: () => null,
      querySelectorAll: () => [], addEventListener: noop, body: el(), head: el(),
      documentElement: el(), title: "",
    }),
    navigator: { userAgent: "node" },
    location: { pathname: "/", hash: "", href: "https://thetalusfieldjournal.com/" },
    history: { pushState: noop, replaceState: noop },
    console,
    setTimeout: noop, clearTimeout: noop, setInterval: () => 0, clearInterval: noop,
    requestAnimationFrame: noop, cancelAnimationFrame: noop,
    fetch: () => Promise.resolve({ ok: false }),
    matchMedia: () => ({ matches: false, addListener: noop }),
    localStorage: { getItem: () => null, setItem: noop },
    Date,
  };
  sandbox.window = sandbox;
  sandbox.globalThis = sandbox;

  // Data globals read during a first render. safeStorage returns null for
  // everything, which is what makes isSubscribed() false — the correct
  // first-visit state, and the one the shell is allowed to bake.
  sandbox.window.SITE = site;
  sandbox.window.ARTICLES = [];
  sandbox.window.CATEGORIES = [];
  sandbox.window.START_HERE = [];
  sandbox.window.safeStorage = { get: () => null, set: () => false, remove: () => false, getJSON: () => null, setJSON: () => false };
  sandbox.window.byCategory = () => [];
  sandbox.window.findArticle = () => null;
  sandbox.window.findCategory = () => ({ label: "", slug: "" });
  sandbox.window.routeToPath = routeToPath;
  // No IntersectionObserver and no track(): impression hooks and analytics are
  // effects, which renderToStaticMarkup never runs.

  vm.createContext(sandbox);
  return sandbox;
}

// ---------------------------------------------------------------------------
// Date-derived slots. Each is blanked to a non-breaking space so the line box
// keeps its height when React fills it in on boot.
// ---------------------------------------------------------------------------
const BLANK = "&nbsp;";
// One slot since the nav simplification pass removed the masthead's dateline:
// the hero kicker's issue label.
const DATE_SLOTS = [
  {
    what: "hero issue label (window.SITE.issueDetail tracks the current month)",
    // <span data-shell-blank="issue">Vol. III · No. 19 · The July Issue</span>
    re: /(<span data-shell-blank="issue"[^>]*>)[\s\S]*?(<\/span>)/,
  },
];

function blankDateSlots(html) {
  let out = html;
  for (const slot of DATE_SLOTS) {
    if (!slot.re.test(out)) {
      console.error(
        `gen-home-shell: could not find the ${slot.what} in the rendered markup.\n` +
          "A date-derived slot moved or was renamed. Fix the pattern in DATE_SLOTS " +
          "(or drop the slot if it is no longer date-derived) — do NOT bake a date " +
          "into index.html, which is cached hard."
      );
      process.exit(2);
    }
    out = out.replace(slot.re, `$1${BLANK}$2`);
  }
  return out;
}

// ---------------------------------------------------------------------------
// Render
// ---------------------------------------------------------------------------
const site = loadSite();
const sandbox = buildSandbox(site);

for (const f of SOURCES) {
  const src = fs.readFileSync(path.join(ROOT, f), "utf8");
  try {
    vm.runInContext(compile(src, f), sandbox, { filename: f });
  } catch (e) {
    console.error(`gen-home-shell: ${f} failed to evaluate under node:vm:\n${e.stack}`);
    process.exit(2);
  }
}

for (const name of ["Header", "HomeHero"]) {
  if (typeof sandbox.window[name] !== "function") {
    console.error(`gen-home-shell: ${name} was not registered on window by ${SOURCES.join(" + ")}.`);
    process.exit(2);
  }
}

const noop = () => {};
let rendered;
try {
  // The hero is wrapped in <main id="main" tabindex="-1"><div class="page">,
  // mirroring the structure app.jsx renders around HomePage. Two reasons: the
  // Header's skip link targets #main, which otherwise does not exist until
  // React mounts (a dangling skip link and a landmark-free page for the whole
  // pre-boot window the shell exists to serve), and landmark parity keeps the
  // shell markup-identical to the first React commit. The duplicate id lasts
  // only the swap frame: createRoot().render() replaces #root's children and
  // app.jsx removes any leftover #home-shell.
  rendered = renderToStaticMarkup(
    React.createElement(
      "div",
      { id: "home-shell" },
      React.createElement(sandbox.window.Header, { current: "home", go: noop }),
      React.createElement(
        "main",
        { id: "main", tabIndex: -1 },
        React.createElement(
          "div",
          { className: "page" },
          React.createElement(sandbox.window.HomeHero, { go: noop })
        )
      )
    )
  );
} catch (e) {
  console.error(
    "gen-home-shell: rendering the shell threw. The hero and masthead must render " +
      "without browser APIs on their first pass (no fetch, no storage, no observers).\n" +
      e.stack
  );
  process.exit(2);
}

// ---------------------------------------------------------------------------
// Normalize away artifacts of rendering with a different React than the one the
// browser loads. scripts/ builds against react-dom 19; the site ships React
// 18.3.1 from /vendor. Two differences show up in static markup:
//   - React 19 serializes some props in camelCase (srcSet, referrerPolicy).
//     HTML parses attribute names case-insensitively so both behave the same,
//     but the shipped file should read like the HTML React 18 writes.
//   - React 19 hoists a <link rel="preload"> for eager images ahead of the
//     markup. It would land OUTSIDE #home-shell and so survive the Worker's
//     removal on every other route. Drop it; the parser reaches the real <img>
//     a few hundred bytes later anyway.
// ---------------------------------------------------------------------------
function normalizeMarkup(html) {
  let out = html;
  const hoisted = out.match(/^(?:<link\b[^>]*>)+/);
  if (hoisted) out = out.slice(hoisted[0].length);
  if (!out.startsWith('<div id="home-shell">')) {
    console.error(
      "gen-home-shell: rendered markup does not start with the #home-shell wrapper " +
        `(starts with: ${out.slice(0, 80)}). React emitted something unexpected ahead of it.`
    );
    process.exit(2);
  }
  return out.replace(/ srcSet=/g, " srcset=").replace(/ referrerPolicy=/g, " referrerpolicy=");
}

rendered = normalizeMarkup(rendered);
rendered = blankDateSlots(rendered);

// Sanity assertions: the point of the shell is that the LCP text and the
// primary ask are in the static HTML. If a refactor drops one, fail here.
const MUST_CONTAIN = [
  ['<h1>Yosemite, from the inside.', "the hero h1"],
  ['class="hero__dek"', "the hero dek (the measured LCP element)"],
  ['Plan my Yosemite trip', "the primary CTA"],
  ['href="/conditions"', "the secondary CTA"],
  ['class="home-edition"', "the edition rule"],
  ['class="masthead"', "the masthead"],
  ['class="bottomnav"', "the mobile bottom nav"],
  ['<main id="main" tabindex="-1">', "the main landmark (the skip link's pre-boot target)"],
];
for (const [needle, what] of MUST_CONTAIN) {
  if (!rendered.includes(needle)) {
    console.error(`gen-home-shell: rendered shell is missing ${what} (${needle}).`);
    process.exit(2);
  }
}
// Backstop for a NEW date-derived slot appearing in the hero or masthead: look
// at the visible text only (so responsive-image widths in srcset attributes are
// not mistaken for years) and reject a four-digit year or the current month
// name. If this fires, either make the value dynamic or add it to DATE_SLOTS.
const visibleText = rendered.replace(/<[^>]*>/g, " ");
const thisMonth = new Date().toLocaleDateString("en-US", { month: "long" });
const dateLeak = visibleText.match(/\b(?:19|20)\d{2}\b/) || visibleText.match(new RegExp(`\\b${thisMonth}\\b`));
if (dateLeak) {
  console.error(
    `gen-home-shell: the rendered shell's text contains "${dateLeak[0]}", which looks date-derived.\n` +
      "index.html is cached hard, so this would ship frozen. Blank the slot via DATE_SLOTS, " +
      "or make the copy date-free."
  );
  process.exit(2);
}

const block = [START, rendered, END].join("\n");

const html = fs.readFileSync(INDEX, "utf8");
const startAt = html.indexOf(START);
const endAt = html.indexOf(END);
if (startAt === -1 || endAt === -1 || endAt < startAt) {
  console.error(
    "index.html is missing the GENERATED:HOME-SHELL markers; cannot regenerate safely.\n" +
      `Expected:\n  ${START}\n  ...\n  ${END}`
  );
  process.exit(2);
}

const current = html.slice(startAt, endAt + END.length);
if (current === block) {
  console.log("index.html home shell is up to date.");
  process.exit(0);
}

if (CHECK) {
  console.error("stale: the home shell in index.html does not match page-home.jsx / components.jsx.");
  console.error("Run: npm --prefix scripts run home-shell");
  process.exit(1);
}

fs.writeFileSync(INDEX, html.slice(0, startAt) + block + html.slice(endAt + END.length));
console.log(`wrote the home shell into index.html (${rendered.length} bytes of markup).`);
